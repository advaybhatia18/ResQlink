-- Replace status check constraint safely to support operational lifecycle
do $$
declare
    existing_constraint text;
begin
    select conname into existing_constraint
    from pg_constraint
    where conrelid = 'public.emergencies'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%status%ACTIVE%RESOLVED%'
      and conname <> 'emergencies_status_check';

    if existing_constraint is not null then
        execute format('alter table public.emergencies drop constraint %I', existing_constraint);
    end if;

    if exists (
        select 1 from pg_constraint
        where conrelid = 'public.emergencies'::regclass
          and conname = 'emergencies_status_check'
    ) then
        alter table public.emergencies drop constraint emergencies_status_check;
    end if;

    alter table public.emergencies
        add constraint emergencies_status_check
        check (status in ('ACTIVE', 'ACKNOWLEDGED', 'DISPATCHED', 'RESOLVED'));
end;
$$;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.emergencies'::regclass
          and conname = 'emergencies_category_check'
    ) then
        alter table public.emergencies
            add constraint emergencies_category_check
            check (
                category in (
                    'MEDICAL',
                    'ROAD_ACCIDENT',
                    'FIRE',
                    'THEFT',
                    'PERSONAL_SAFETY',
                    'NATURAL_DISASTER',
                    'OTHER'
                )
            ) not valid;
    end if;
end;
$$;

