    on public.emergency_status_history
    for select
    to authenticated
    using (
        exists (
            select 1
            from public.emergencies as e
            where e.id = emergency_id
              and (
                  e.user_id = (select auth.uid())
                  or exists (
                      select 1
                      from public.profiles as p
                      where p.id = (select auth.uid())
                        and p.role = 'ADMIN'
                  )
              )
        )
    );

