-- 3. Emergency contacts table
create table if not exists public.emergency_contacts (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles (id) on delete cascade,
    name text not null check (char_length(trim(name)) between 1 and 100),
    phone text not null check (char_length(trim(phone)) between 5 and 32),
    relationship text not null check (char_length(trim(relationship)) between 1 and 60),
    is_primary boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists emergency_contacts_user_phone_idx
    on public.emergency_contacts (user_id, phone);
create unique index if not exists emergency_contacts_one_primary_idx
    on public.emergency_contacts (user_id)
    where is_primary = true;
create index if not exists emergency_contacts_user_id_idx
    on public.emergency_contacts (user_id);

alter table public.emergency_contacts enable row level security;
revoke all on public.emergency_contacts from anon, authenticated;
revoke all on sequence public.emergency_contacts_id_seq from anon, authenticated;
grant select, insert, update, delete on public.emergency_contacts to authenticated, service_role;
grant usage, select on sequence public.emergency_contacts_id_seq to authenticated, service_role;

drop policy if exists "Users manage own emergency contacts" on public.emergency_contacts;
create policy "Users manage own emergency contacts"
    on public.emergency_contacts
    for all
    to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()));

