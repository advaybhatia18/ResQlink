create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    name text not null,
    role text not null default 'USER' check (role in ('USER', 'ADMIN')),
    created_at timestamptz not null default now()
);

create table if not exists public.emergencies (
    id bigint generated by default as identity primary key,
    severity integer not null check (severity between 1 and 5),
    label text not null,
    priority integer not null,
    status text not null default 'ACTIVE'
        check (status in ('ACTIVE', 'RESOLVED')),
    created_at timestamptz not null default now(),
    latitude double precision,
    longitude double precision,
    check (latitude is null or latitude between -90 and 90),
    check (longitude is null or longitude between -180 and 180)
);

alter table public.profiles enable row level security;
alter table public.emergencies enable row level security;

grant select on public.profiles to service_role;
grant select, insert, update on public.emergencies to service_role;
grant usage, select on sequence public.emergencies_id_seq to service_role;

create or replace function public.handle_new_resqlink_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, name)
    values (
        new.id,
        coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), 'User')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_resqlink_auth_user_created on auth.users;
create trigger on_resqlink_auth_user_created
    after insert on auth.users
    for each row execute procedure public.handle_new_resqlink_user();
