create table if not exists public.emergencies (
    id bigint generated by default as identity primary key,
    severity integer not null check (severity between 1 and 5),
    label text not null,
    priority integer not null,
    status text not null default 'ACTIVE'
        check (status in ('ACTIVE', 'ACKNOWLEDGED', 'DISPATCHED', 'RESOLVED')),
    category text not null default 'PERSONAL_SAFETY'
        check (
            category in (
                'MEDICAL',
                'ROAD_ACCIDENT',
                'FIRE',
                'THEFT',
                'PERSONAL_SAFETY',
                'NATURAL_DISASTER',
                'OTHER'
            )
        ),
    recommended_services text[] not null default '{}',
    requested_services text[] not null default '{}',
    notes text,
    admin_notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    acknowledged_at timestamptz,
    resolved_at timestamptz,
    user_id uuid references public.profiles (id) on delete cascade,
    idempotency_key uuid,
    latitude double precision,
    longitude double precision,
    location_accuracy_m double precision,
    constraint emergencies_coordinates_paired_check
        check (
            (latitude is null and longitude is null)
            or (latitude is not null and longitude is not null)
        ),
    constraint emergencies_latitude_range_check
        check (latitude is null or latitude between -90 and 90),
    constraint emergencies_longitude_range_check
        check (longitude is null or longitude between -180 and 180),
    constraint emergencies_location_accuracy_check
        check (location_accuracy_m is null or location_accuracy_m >= 0)
);

